export const normalizeLanguage = (lang: string | null | undefined): string => {
  if (!lang) return '';
  const cleaned = lang.trim().toLowerCase();
  const base = cleaned.split(/[-_]/)[0];
  return base || '';
};

export const isRTL = (lang: string | null | undefined): boolean => {
  const normalized = normalizeLanguage(lang);
  return ['he', 'ar', 'fa', 'ur', 'yi'].includes(normalized);
};

export const getUIStrings = (lang: string | null | undefined): UIStrings => {
  const normalized = normalizeLanguage(lang);
  const localized = normalized ? TRANSLATIONS[normalized] : undefined;
  return localized ? { ...EN_STRINGS, ...localized } : EN_STRINGS;
};

export async function getSiteLanguage(): Promise<string | null> {
  try {
    if (typeof window === 'undefined') return null;
    if (typeof multilingual?.isEnabled === 'function') {
      const enabled = await multilingual.isEnabled();
      if (enabled && typeof multilingual.currentLanguage === 'function') {
        const current = await multilingual.currentLanguage();
        if (typeof current === 'string' && current.trim()) {
          return normalizeLanguage(current);
        }
      }
    }
    const htmlLang = typeof document !== 'undefined' ? document.documentElement?.lang : undefined;
    if (htmlLang) return normalizeLanguage(htmlLang);
  } catch {
    // In preview, tests, or non-multilingual site context
  }
  return null;
}
